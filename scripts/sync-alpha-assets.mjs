import { mkdir, writeFile } from 'node:fs/promises';

const SOURCE = Object.freeze({
  repository: 'GargantuaX/gemini-watermark-remover',
  commit: 'a771bc28df7e6af97dd862d5f293157207ba6d58',
  path: 'src/core/embeddedAlphaMaps.js'
});
const RAW_URL = `https://raw.githubusercontent.com/${SOURCE.repository}/${SOURCE.commit}/${SOURCE.path}`;
const TARGET = new URL('../src/vendor/alphaPayload.js', import.meta.url);
const META_TARGET = new URL('../public/alpha/alpha-source.json', import.meta.url);
const KEYS = ['48', '96', '96-20260520'];

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function extractMap(source, key) {
  const escaped = escapeRegExp(key);
  const patterns = [
    new RegExp(`['\"]${escaped}['\"]\\s*:\\s*'([^']+)'`),
    new RegExp(`(?:^|\\n)\\s*${escaped}\\s*:\\s*'([^']+)'`)
  ];
  for (const pattern of patterns) {
    const match = source.match(pattern);
    if (match?.[1]) return match[1];
  }
  throw new Error(`Could not find embedded alpha map: ${key}`);
}

const response = await fetch(RAW_URL, {
  headers: { 'user-agent': 'gemini-video-watermark-cleaner-setup' }
});
if (!response.ok) throw new Error(`Failed to fetch alpha source: HTTP ${response.status}`);
const text = await response.text();
const maps = Object.fromEntries(KEYS.map((key) => [key, extractMap(text, key)]));

for (const [key, base64] of Object.entries(maps)) {
  const bytes = Buffer.from(base64, 'base64');
  if (bytes.byteLength % 4 !== 0) throw new Error(`Alpha map ${key} is not Float32-aligned`);
  const floatCount = bytes.byteLength / 4;
  const expected = key === '48' ? 48 * 48 : 96 * 96;
  if (floatCount !== expected) throw new Error(`Alpha map ${key} has ${floatCount} floats; expected ${expected}`);
}

const moduleText = `// AUTO-GENERATED by scripts/sync-alpha-assets.mjs. Do not edit by hand.\n` +
`export const ALPHA_SOURCE = Object.freeze(${JSON.stringify({ ...SOURCE, synced: true }, null, 2)});\n\n` +
`export const ALPHA_MAPS = Object.freeze(${JSON.stringify(maps, null, 2)});\n`;

await mkdir(new URL('../src/vendor/', import.meta.url), { recursive: true });
await mkdir(new URL('../public/alpha/', import.meta.url), { recursive: true });
await writeFile(TARGET, moduleText, 'utf8');
await writeFile(META_TARGET, JSON.stringify({ ...SOURCE, rawUrl: RAW_URL, maps: KEYS }, null, 2) + '\n', 'utf8');
console.log(`Synced ${KEYS.length} alpha profiles from ${SOURCE.repository}@${SOURCE.commit.slice(0, 12)}`);
